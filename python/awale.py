# Beginner coach (mirrors Coach.looksAt / simpleBest / checkTrap in src/advisor.js)
# ---------------------------------------------------------------------------

def looks_at(state: State) -> list[dict]:
    """For each legal move: seeds won now (take) and the most the opponent can grab right after (risk)."""
    out = []
    for pit in legal_moves(state):
        sim = simulate(state, pit)
        risk, risk_from, risk_pits = 0, None, []
        for r in legal_moves(sim["after"]):
            rs = simulate(sim["after"], r)
            if rs["captured"] > risk:
                risk, risk_from = rs["captured"], r
                risk_pits = [p for p in range(PITS) if owner(p) == state.to_move
                             and rs["after"].board[p] == 0 and sim["after"].board[p] + rs["sown"].count(p) in (2, 3)]
        if sim["after"].stores[owner(pit)] >= SEEDS_TO_WIN:
            risk = 0
        out.append({"pit": pit, "take": sim["captured"], "grand_slam": sim["grand_slam"],
                    "risk": risk, "risk_from": risk_from, "risk_pits": risk_pits,
                    "net": sim["captured"] - risk})
    return out


def simple_best(looks: list[dict]) -> dict:
    # Same ordering as JS: best net, then most taken, then least risk; ties keep pit order (stable sort).
    return sorted(looks, key=lambda l: (-l["net"], -l["take"], l["risk"]))[0]


def check_trap(state: State, pit: int) -> dict | None:
    looks = looks_at(state)
    mine = next((l for l in looks if l["pit"] == pit), None)
    if mine is None or len(looks) < 2:
        return None
    better = simple_best(looks)
    if better["pit"] == pit or better["net"] - mine["net"] < 2:
        return None
    if mine["grand_slam"] and better["take"] > 0:
        kind = "grand-slam"
    elif mine["risk"] - better["risk"] >= 2:
        kind = "danger"
    else:
        kind = "missed"
    return {"kind": kind, "mine": mine, "better": better}
