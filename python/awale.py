from __future__ import annotations

from dataclasses import dataclass, field

PITS, SIDE, SEEDS_TO_WIN = 12, 6, 25
PIT_NAMES = list("abcdefABCDEF")


def owner(pit: int) -> int:
    return 0 if pit < SIDE else 1


def side_sum(board, player: int) -> int:
    o = player * SIDE
    return sum(board[o:o + SIDE])


@dataclass
class State:
    board: list = field(default_factory=lambda: [4] * PITS)
    stores: list = field(default_factory=lambda: [0, 0])
    to_move: int = 0

    def copy(self) -> "State":
        return State(self.board[:], self.stores[:], self.to_move)

    def key(self) -> str:
        return f"{self.to_move}:" + ",".join(map(str, self.board))


def simulate(state: State, pit: int) -> dict:
    """Sow + capture with no legality check. Mirrors engine.js simulate()."""
    board, stores = state.board[:], state.stores[:]
    player, opp = owner(pit), 1 - owner(pit)
    seeds, board[pit] = board[pit], 0
    i, sown = pit, []
    while seeds:
        i = (i + 1) % PITS
        if i == pit:
            continue
        board[i] += 1
        sown.append(i)
        seeds -= 1
    captures, j = [], i
    while owner(j) == opp and board[j] in (2, 3):
        captures.append((j, board[j]))
        j = (j - 1) % PITS
    total = sum(n for _, n in captures)
    grand_slam = bool(captures) and total == side_sum(board, opp)
    if not grand_slam:
        for p, _ in captures:
            board[p] = 0
        stores[player] += total
    return {
        "sown": sown, "last": i, "captured": 0 if grand_slam else total,
        "grand_slam": grand_slam, "after": State(board, stores, opp),
    }


def move_status(state: State, pit: int) -> str:
    if owner(pit) != state.to_move:
        return "not-your-side"
    if state.board[pit] == 0:
        return "empty"
    opp = 1 - state.to_move
    if side_sum(state.board, opp) == 0:
        dist = (opp * SIDE - pit) % PITS
        if state.board[pit] < dist:
            return "must-feed"
    return "ok"


def legal_moves(state: State) -> list[int]:
    o = state.to_move * SIDE
    return [p for p in range(o, o + SIDE) if move_status(state, p) == "ok"]


def winner_of(stores) -> int | None:
    return 0 if stores[0] > stores[1] else 1 if stores[1] > stores[0] else None


def check_end(state: State, history: dict | None = None) -> dict | None:
    s = state.stores
    if s[0] >= SEEDS_TO_WIN:
        return {"winner": 0, "reason": "majority", "stores": s[:]}
    if s[1] >= SEEDS_TO_WIN:
        return {"winner": 1, "reason": "majority", "stores": s[:]}
    if s == [24, 24]:
        return {"winner": None, "reason": "draw", "stores": s[:]}
    if not legal_moves(state):
        stores = s[:]
        stores[state.to_move] += sum(state.board)
        return {"winner": winner_of(stores), "reason": "no-moves", "stores": stores}
    if history and history.get(state.key(), 0) >= 3:
        stores = [s[0] + side_sum(state.board, 0), s[1] + side_sum(state.board, 1)]
        return {"winner": winner_of(stores), "reason": "repetition", "stores": stores}
    return None


class Awale:
    """Small gym-style wrapper. Reward is the seeds captured by the mover this step,
    plus +/-48 for a win/loss at the end (from the mover's perspective)."""

    def __init__(self, first_player: int = 0):
        self.first_player = first_player
        self.reset()

    def reset(self) -> list[int]:
        self.state = State(to_move=self.first_player)
        self.history = {self.state.key(): 1}
        self.result = None
        return self.observation()

    @property
    def done(self) -> bool:
        return self.result is not None

    def legal_moves(self) -> list[int]:
        return legal_moves(self.state)

    def observation(self) -> list[int]:
        """Board rotated so the side to move is always pits 0-5, then both stores."""
        s = self.state
        b = s.board if s.to_move == 0 else s.board[6:] + s.board[:6]
        return b + [s.stores[s.to_move], s.stores[1 - s.to_move]]

    def step(self, pit: int):
        status = move_status(self.state, pit)
        if status != "ok":
            raise ValueError(f"illegal move {pit}: {status}")
        mover = self.state.to_move
        sim = simulate(self.state, pit)
        self.state = sim["after"]
        k = self.state.key()
        self.history[k] = self.history.get(k, 0) + 1
        self.result = check_end(self.state, self.history)
        reward = sim["captured"]
        if self.result and self.result["winner"] is not None:
            reward += 48 if self.result["winner"] == mover else -48
        return self.observation(), reward, self.done, {"sim": sim, "result": self.result}


