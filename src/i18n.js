  function t(key, params) {
    let s = (S[lang] && S[lang][key]) ?? S.en[key] ?? key;
    if (params) {
      s = s.replace(/\{(\w+)\}/g, (m, k) => {
        if (k in params) return params[k];
        const lower = k.charAt(0).toLowerCase() + k.slice(1);
        if (k !== lower && lower in params) { const v = String(params[lower]); return v.charAt(0).toUpperCase() + v.slice(1); }
        return m;
      });
    }
    return s;
  }

