// Bao puzzles: positions from realistic games where one move is clearly best for a beginner
// (the coach's one-move-ahead check: captured now minus what the opponent can capture right after).
//   node tools/make_bao_puzzles.js   -> writes src/bao/puzzles.js
// Kinds:
//   win     capture the most seeds (and stay safe)
//   defend  every capture is small; one move leaves much less for the opponent
//   greedy  the biggest capture is a trap; a smaller one is clearly better
//   game    one move empties the opponent's front row and wins
const fs = require('fs');
const path = require('path');
const B = require('../src/bao/engine.js');
const A = require('../src/bao/advisor.js');

function mulberry32(a) { return function () { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const rng = mulberry32(7);
const WANT = { win: 9, defend: 9, greedy: 8, game: 6 };
const GAP = 4;

function classify(s) {
  const looks = A.looksAt(s);
  if (looks.length < 3) return null;
  const sorted = looks.slice().sort((a, b) => b.net - a.net);
  const best = sorted[0], second = sorted[1];
  if (best.net - second.net < GAP) return null;
  // Same pit, other direction, equally good? Then the puzzle has two answers.
  if (looks.some((l) => l !== best && l.net > best.net - GAP)) return null;
  const maxOtherTake = Math.max(...looks.filter((l) => l !== best).map((l) => l.take));
  if (best.take >= 64) return looks.filter((l) => l.take >= 64).length === 1 ? { type: 'game', best } : null;
  if (best.risk >= 64) return null;
  if (best.take > 0 && maxOtherTake > best.take + 2) return { type: 'greedy', best };
  if (best.take >= 4 && best.take > maxOtherTake + 2 && best.risk <= 2) return { type: 'win', best };
  if (best.take <= maxOtherTake && best.risk <= 2 && looks.filter((l) => l.risk >= best.risk + GAP).length >= 2) return { type: 'defend', best };
  return null;
}

const out = [];
const seen = new Set();
const count = { win: 0, defend: 0, greedy: 0, game: 0 };
for (let g = 0; g < 4000 && Object.keys(WANT).some((k) => count[k] < WANT[k]); g++) {
  let s = B.newGame(0);
  for (let ply = 0; ply < 120; ply++) {
    if (B.checkEnd(s)) break;
    if (s.toMove === 0 && ply >= 4) {
      const c = classify(s);
      const key = B.positionKey(s);
      if (c && count[c.type] < WANT[c.type] && !seen.has(key)) {
        seen.add(key);
        count[c.type]++;
        out.push({ id: 'b' + (out.length + 1), type: c.type, pits: [s.pits[0].slice(), s.pits[1].slice()], answer: { pit: c.best.pit, dir: c.best.dir } });
      }
    }
    const level = rng() < 0.5 ? 'easy' : 'medium';
    const m = A.chooseMove(s, level, { adaptive: false, rng });
    s = B.play(s, { pit: m.pit, dir: m.dir }).state;
  }
}
// Interleave kinds so the list starts varied, easy kinds first.
const order = ['win', 'game', 'defend', 'greedy'];
const byType = Object.fromEntries(order.map((t) => [t, out.filter((p) => p.type === t)]));
const mixed = [];
for (let i = 0; mixed.length < out.length; i++) for (const t of order) if (byType[t][i]) mixed.push(byType[t][i]);
mixed.forEach((p, i) => { p.id = 'b' + (i + 1); });

const body = '// Generated by tools/make_bao_puzzles.js. Do not edit by hand.\n(function (root) {\n  const PUZZLES = ' +
  JSON.stringify(mixed).replace(/\},\{"id"/g, '},\n    {"id"') +
  ';\n  if (typeof module !== \'undefined\' && module.exports) module.exports = PUZZLES;\n  root.Bao = root.Bao || {};\n  root.Bao.PUZZLES = PUZZLES;\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(__dirname, '../src/bao/puzzles.js'), body);
console.log('puzzles', mixed.length, count);
