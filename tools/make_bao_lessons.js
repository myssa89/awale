// Finds clear, small Bao lesson positions that satisfy each lesson's teaching goal.
//   node tools/make_bao_lessons.js   -> writes src/bao/lessons.js
const fs = require('fs');
const path = require('path');
const B = require('../src/bao/engine.js');
function mulberry32(a) { return function () { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const rng = mulberry32(42);
const rnd = (n) => Math.floor(rng() * n);

function randomSide(density, max) {
  const a = new Array(16).fill(0);
  for (let k = 0; k < 16; k++) if (rng() < density) a[k] = 1 + rnd(max);
  return a;
}
const total = (s) => B.sideSum(s, 0) + B.sideSum(s, 1);
const results = (s) => B.legalMoves(s).map((m) => ({ m, r: B.play(s, m) }));

const SPECS = {
  board: (s, R) => R.length >= 4 && R.every((x) => !x.m.capture && x.r.sowings === 1) && B.innerSum(s, 1) >= 4,
  relay: (s, R) => R.every((x) => !x.m.capture) && R.some((x) => x.r.sowings >= 2) && R.some((x) => x.r.sowings === 1) && R.filter((x) => x.r.sowings >= 2).length <= 2,
  capture: (s, R) => R.length >= 1 && R.length <= 2 && R.every((x) => x.m.capture) && R.every((x) => x.r.captures === 1 && x.r.sowings <= 3)
    && B.legalMoves(Object.assign({}, s)).length > 0 && countPlayable(s) >= 3,
  ends: (s, R) => R.length === 1 && R[0].m.capture && R[0].r.captures === 1 && endCapture(R[0].r) && countPlayable(s) >= 3,
  must: (s, R) => R.length >= 1 && R.length <= 2 && R.every((x) => x.m.capture) && countPlayable(s) - new Set(R.map((x) => x.m.pit)).size >= 2,
  back: (s, R) => R.length >= 2 && R.every((x) => !x.m.capture && x.m.pit >= 8) && s.pits[0].slice(0, 8).some((n) => n === 1),
  win: (s, R) => R.length >= 2 && R.filter((x) => !B.checkEnd(x.r.state) ? false : B.checkEnd(x.r.state).winner === 0).length === 1,
};
function countPlayable(s) { return s.pits[0].filter((n) => n >= 2).length; }
function endCapture(r) { const c = r.events.find((e) => e.t === 'capture'); return c && (c.k <= 1 || c.k >= 6); }

const found = {};
for (const id of Object.keys(SPECS)) {
  let best = null;
  for (let i = 0; i < 400000 && (!best || i < 60000); i++) {
    const s = { pits: [randomSide(0.35, 3), randomSide(0.35, 3)], toMove: 0 };
    if (id === 'back') for (let k = 0; k < 8; k++) if (s.pits[0][k] > 1) s.pits[0][k] = 1;
    if (B.checkEnd(s)) continue;
    if (B.innerSum(s, 1) === 0) continue;
    const R = results(s);
    if (!SPECS[id](s, R)) continue;
    const score = total(s);
    if (score < 14) continue; // not too empty
    if (!best || score < best.score) best = { s, score };
  }
  if (!best) throw new Error('no position for ' + id);
  found[id] = best.s;
  console.log(id, best.score, JSON.stringify(best.s.pits));
}

const GOALS = {
  board: { type: 'any' }, relay: { type: 'relay' }, capture: { type: 'capture' }, ends: { type: 'capture' },
  must: { type: 'any' }, back: { type: 'any' }, win: { type: 'win' },
};
const lessons = Object.keys(SPECS).map((id) => ({ id, pits: found[id].pits, goal: GOALS[id] }));
const out = `/*
 * Bao lessons (learners' rules). Positions generated by tools/make_bao_lessons.js and checked by
 * tests/bao.test.js. Text for each lesson lives in i18n.js (Bao lesson texts).
 * goal.type: any | relay (a move with 2+ sowings) | capture | win
 */
(function (root) {
  'use strict';
  const LESSONS = [
${lessons.map((l) => '    ' + JSON.stringify(l)).join(',\n')},
  ];
  if (typeof module !== 'undefined' && module.exports) module.exports = LESSONS;
  root.Bao = root.Bao || {};
  root.Bao.LESSONS = LESSONS;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'bao', 'lessons.js'), out);
